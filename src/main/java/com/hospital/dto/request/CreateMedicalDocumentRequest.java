package com.hospital.dto.request;

import com.hospital.entity.MedicalDocumentType;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.NotNull;
import lombok.Data;

import java.time.LocalDate;

/**
 * DTO ЗАПРОСА — создание нового медицинского документа врачом
 *
 * Используется в теле POST-запроса:
 *   POST /api/doctor/documents
 *
 * Доступен только пользователям с ролью ROLE_DOCTOR.
 * Автор документа (doctorId) НЕ передаётся в запросе — определяется сервером
 * из SecurityContext (JWT токена), что исключает подделку авторства.
 *
 * Поля, устанавливаемые сервером автоматически (не входят в этот DTO):
 *   - doctorId  — из текущего аутентифицированного пользователя
 *   - issuedAt  — текущее время сервера (LocalDateTime.now())
 *   - active    — всегда true при создании
 *
 * Валидация выполняется аннотациями Bean Validation (Jakarta EE).
 * Контроллер помечает параметр @Valid, Spring вызывает валидатор до входа в сервис.
 * При нарушении ограничения возвращается HTTP 400 с деталями ошибки.
 */
@Data // Lombok: геттеры/сеттеры (Jackson использует при десериализации JSON-тела),
      // equals/hashCode/toString — удобны при отладке и юнит-тестировании.
public class CreateMedicalDocumentRequest {

    /**
     * ID пациента (Patient.id), для которого создаётся документ.
     *
     * @NotNull — обязательное поле: без пациента документ лишён смысла.
     *   Использован @NotNull, а не @NotBlank, потому что поле числовое (Long),
     *   а не строковое. @NotBlank применим только к CharSequence.
     *
     * Сервис дополнительно проверяет, что:
     *   1. Пациент с таким ID существует (иначе EntityNotFoundException)
     *   2. Пациент активен (active = true, не soft-deleted)
     *   3. Врач имеет право создавать документы этому пациенту (опционально)
     */
    @NotNull(message = "Укажите пациента")
    private Long patientId;

    /**
     * Тип медицинского документа из перечисления MedicalDocumentType.
     *
     * @NotNull — обязательное поле: тип определяет юридическую форму документа,
     *   правила срока действия и шаблон отображения.
     *
     * Jackson десериализует строку («PRESCRIPTION») в enum-константу автоматически.
     * При передаче несуществующего значения Jackson бросает HttpMessageNotReadableException
     * → HTTP 400. Дополнительной валидации не требуется.
     *
     * Альтернатива — String с @Pattern: отклонена, так как enum даёт типобезопасность
     * на уровне компилятора и явный список допустимых значений в Swagger-документации.
     */
    @NotNull(message = "Укажите тип документа")
    private MedicalDocumentType type;

    /**
     * Краткий заголовок документа (человекочитаемый).
     *
     * @NotBlank — обязательное непустое строковое поле.
     *   Отображается в списке документов пациента как основной текст строки
     *   (например, «Рецепт: Амоксициллин 500мг» или «Больничный №ВК-12345»).
     *   Без заголовка пользователь не сможет отличить документы в списке.
     *
     * Ограничение длины (@Size) не задано — контролируется на уровне колонки в БД.
     * При необходимости добавить: @Size(max = 500).
     */
    @NotBlank(message = "Заголовок обязателен")
    private String title;

    /**
     * Полный текст документа — детальное содержание.
     *
     * @NotBlank — документ без содержания юридически недействителен.
     *   Может включать: состав назначений (рецепт), коды МКБ-10 (больничный),
     *   перечень анализов (направление), произвольный текст (справка).
     *
     * Хранится в БД как TEXT (PostgreSQL) — без ограничения длины на уровне схемы.
     * Ограничение длины может быть добавлено через @Size при необходимости.
     */
    @NotBlank(message = "Содержание документа обязательно")
    private String content;

    /**
     * Дата окончания действия документа (необязательная).
     *
     * Null допустим: часть документов бессрочна (некоторые справки, заключения).
     * Для рецептов и больничных листов заполнение рекомендуется,
     * но не принудительно — врач несёт профессиональную ответственность.
     *
     * Тип LocalDate (только дата, без времени): срок действия измеряется
     * в днях, точность до минут избыточна и вносит путаницу.
     *
     * Фронтенд отображает предупреждение «Срок действия истёк»,
     * если validUntil != null && validUntil.isBefore(LocalDate.now()).
     *
     * Альтернатива @Future — отклонена: врач может оформлять
     * документ задним числом (ретроспективно), что легально.
     */
    private LocalDate validUntil;
}
