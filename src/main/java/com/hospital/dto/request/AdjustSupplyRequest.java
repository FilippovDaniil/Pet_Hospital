package com.hospital.dto.request;

import lombok.Data;

/**
 * DTO для корректировки остатка на складе (PATCH /api/nurse/supplies/{id}/adjust).
 *
 * Используется вместо полного PUT-обновления, чтобы атомарно изменить только количество.
 * Это важно при одновременной работе нескольких медсестёр — каждая применяет свой delta,
 * а не перезаписывает текущее значение (оптимистичная модель без race condition на уровне API).
 */
@Data
public class AdjustSupplyRequest {

    /**
     * Изменение остатка:
     *   + (положительное) — пополнение склада (приход).
     *   - (отрицательное) — расход (выдача медикамента пациенту).
     *
     * Сервис проверяет: quantity + delta >= 0.
     * Если результат отрицательный — бросает BusinessRuleException.
     */
    private int delta;
}
