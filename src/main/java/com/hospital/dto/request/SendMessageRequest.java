package com.hospital.dto.request;

import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.Size;
import lombok.Data;

/**
 * DTO ЗАПРОСА — отправка нового сообщения в чат
 *
 * Используется в теле POST-запроса:
 *   POST /api/client/chats/{roomId}/messages  — клиент отправляет сообщение
 *   POST /api/staff/chats/{roomId}/messages   — сотрудник (врач/администратор) отвечает
 *
 * Намеренно минималистичен: содержит только контент сообщения.
 * Всё остальное (отправитель, время, комната) определяется сервером:
 *   - senderId    — из SecurityContext (JWT текущего пользователя)
 *   - roomId      — из параметра пути URL
 *   - sentAt      — серверное время (LocalDateTime.now()) при сохранении
 *   - read = false — устанавливается автоматически для новых сообщений
 *
 * Такой подход исключает возможность подделки отправителя или времени
 * из клиентского запроса.
 */
@Data // Lombok: генерирует геттер для content (нужен при десериализации Jackson),
      // сеттер (нужен Jackson для заполнения поля из JSON-тела запроса),
      // equals/hashCode/toString — полезны при логировании и тестировании.
public class SendMessageRequest {

    /**
     * ТЕКСТ СООБЩЕНИЯ — единственное поле запроса.
     *
     * Ограничения валидации (проверяются @Valid в контроллере):
     *
     * @NotBlank — сообщение не должно быть null, пустой строкой или состоять
     *   только из пробельных символов. Пользователь не должен иметь возможность
     *   отправить «пустое» сообщение — это бессмысленно и засоряет историю.
     *   Отличие от @NotNull/@NotEmpty: @NotBlank дополнительно обрезает пробелы
     *   перед проверкой (whitespace-aware).
     *
     * @Size(max = 4000) — верхний предел длины.
     *   4000 символов — осознанный выбор:
     *     - Достаточно для развёрнутой врачебной консультации в чате
     *     - PostgreSQL тип TEXT позволяет хранить неограниченно, но без лимита
     *       один злоумышленник может отправить мегабайтное сообщение
     *     - Граница 4000 < 4096 байт в UTF-8 (с запасом на многобайтные символы),
     *       что позволяет передать сообщение в одном TCP-пакете
     *     - Стандарт мессенджеров: Telegram — 4096, WhatsApp — 65536
     */
    @NotBlank(message = "Сообщение не может быть пустым")
    @Size(max = 4000, message = "Сообщение не должно превышать 4000 символов")
    private String content;
}
