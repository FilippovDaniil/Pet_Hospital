package com.hospital.dto.request;

import com.hospital.entity.PatientNoteType;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.NotNull;
import lombok.Data;

/**
 * DTO ЗАПРОСА — создание новой врачебной записи в истории болезни пациента
 *
 * Используется в теле POST-запроса:
 *   POST /api/doctor/patients/{patientId}/notes  — врач создаёт запись
 *
 * Доступен только пользователям с ролью ROLE_DOCTOR.
 * Автор записи (doctorId) НЕ передаётся клиентом — извлекается сервером
 * из SecurityContext (JWT), исключая подделку авторства.
 *
 * Поля, устанавливаемые сервером автоматически (не входят в DTO):
 *   - doctorId  — из аутентифицированного пользователя (SecurityContext)
 *   - createdAt — текущее время сервера (LocalDateTime.now())
 *
 * Валидация Bean Validation срабатывает при наличии @Valid в контроллере
 * до вызова сервисного метода. Нарушение → HTTP 400 с телом ошибки.
 */
@Data // Lombok: геттеры/сеттеры для десериализации Jackson из JSON-тела запроса,
      // toString/equals/hashCode — для логов и тестов.
public class CreatePatientNoteRequest {

    /**
     * ID пациента (Patient.id), к истории болезни которого добавляется запись.
     *
     * @NotNull — обязательное поле: запись без привязки к пациенту бессмысленна.
     *   Числовой тип Long — @NotBlank неприменим (только для строк).
     *
     * Сервис проверяет:
     *   1. Пациент с ID существует (иначе EntityNotFoundException → HTTP 404)
     *   2. Пациент не удалён мягко (active = true, иначе HTTP 404)
     *
     * Примечание: patientId может также приходить как path variable ({patientId}).
     * В таком случае это поле избыточно — архитектурный выбор оставлен на усмотрение
     * команды (body vs path; унификация с CreateMedicalDocumentRequest — в body).
     */
    @NotNull(message = "Укажите пациента")
    private Long patientId;

    /**
     * Тип врачебной записи из перечисления PatientNoteType.
     *
     * @NotNull — обязательное поле: тип определяет семантику записи
     *   (диагноз, наблюдение или заметка) и правила видимости для пациента.
     *
     * Jackson десериализует строку («DIAGNOSIS») в enum-константу.
     * Неизвестное значение → HttpMessageNotReadableException → HTTP 400.
     *
     * Альтернатива String — отклонена: enum даёт типобезопасность и
     * исчерпывающий список значений в Swagger (ограниченный набор вместо свободной строки).
     */
    @NotNull(message = "Укажите тип записи")
    private PatientNoteType type;

    /**
     * Содержание записи — основной клинический текст, введённый врачом.
     *
     * @NotBlank — запись без содержания лишена клинической ценности и
     *   не должна сохраняться. @NotBlank строже @NotEmpty: дополнительно
     *   отклоняет строки, состоящие только из пробелов («   »).
     *
     * Формат содержания произвольный:
     *   - DIAGNOSIS:    «J06.9 — ОРВИ, средней степени тяжести. Осложнений нет.»
     *   - OBSERVATION:  «АД 130/85, ЧСС 74. Жалобы: головная боль 2 дня. Зев гиперемирован.»
     *   - NOTE:         «Пациент планирует операцию в феврале — учесть при назначении.»
     *
     * Хранится как TEXT в PostgreSQL — без ограничения длины на уровне схемы.
     */
    @NotBlank(message = "Содержание обязательно")
    private String content;

    /**
     * ФЛАГ ВИДИМОСТИ ДЛЯ КЛИЕНТА — управляет, будет ли запись
     * показана пациенту в его личном кабинете.
     *
     * true  — пациент видит запись в разделе «Моя история болезни»
     * false — запись только для персонала (внутренняя; клиент не увидит)
     *
     * Значение по умолчанию false — консервативная политика:
     *   Врач явно принимает решение показать запись пациенту, установив true.
     *   Это защищает от случайного раскрытия служебных заметок
     *   (например, координация с коллегами, сомнения в диагнозе).
     *
     * Альтернативы рассмотрены:
     *   - default = true: опасно — врач может забыть снять флаг у служебной заметки
     *   - Обязательное поле (@NotNull): избыточно — значение по умолчанию удобнее
     *
     * Тип primitive boolean (не Boolean): null-значение не имеет бизнес-смысла.
     */
    private boolean visibleToClient = false;
}
