package com.hospital.dto.response;

import lombok.Builder;
import lombok.Data;

import java.time.LocalDateTime;

/**
 * DTO ОТВЕТА — информация о чат-комнате для клиентского и персонального интерфейса
 *
 * Возвращается API при запросе списка чатов текущего пользователя
 * (GET /api/client/chats или GET /api/staff/chats).
 *
 * Содержит денормализованные данные об участниках (имена, userId) и
 * агрегированную информацию о состоянии чата (lastMessage, unreadCount),
 * чтобы фронтенд мог отрисовать список диалогов без дополнительных запросов.
 *
 * Архитектурное решение — тип комнаты передаётся как String, а не enum:
 *   - Фронтенд не зависит от Java-перечислений
 *   - Строковое значение («SUPPORT», «DOCTOR_CLIENT») напрямую отображается
 *     в метку вкладки без маппинга на стороне клиента
 */
@Data    // Lombok: генерирует геттеры, сеттеры, equals/hashCode, toString.
         // Используем вместо ручного написания ~60 строк бойлерплейта.
@Builder // Lombok: генерирует паттерн Builder — удобно собирать DTO в сервисном слое:
         // ChatRoomResponse.builder().id(room.getId()).type(...).build()
         // без конструкторов с длинным списком аргументов.
public class ChatRoomResponse {

    /**
     * Идентификатор чат-комнаты в БД.
     * Используется фронтендом для запроса истории сообщений:
     * GET /api/client/chats/{id}/messages
     */
    private Long id;

    /**
     * Тип комнаты в виде строки: «SUPPORT» или «DOCTOR_CLIENT».
     * Строковое представление ChatRoomType — фронтенд использует его
     * для выбора иконки и заголовка диалога без дополнительного маппинга.
     */
    private String type;

    /**
     * ID пользователя-клиента (пациента) — участника чата со стороны ROLE_CLIENT.
     * Нужен фронтенду для определения «своей» стороны диалога
     * (чтобы выровнять пузырьки сообщений влево/вправо).
     */
    private Long clientUserId;

    /**
     * Отображаемое имя клиента (обычно fullName из User или username).
     * Денормализовано сюда, чтобы не делать отдельный запрос к /api/users/{id}.
     * Используется персоналом (врач/администратор) в заголовке диалога.
     */
    private String clientUserName;

    /**
     * ID пользователя-сотрудника — участника чата со стороны персонала
     * (ROLE_DOCTOR, ROLE_ADMIN, ROLE_NURSE).
     * При типе DOCTOR_CLIENT совпадает с User.id врача,
     * что позволяет фильтровать чаты врача без JOIN с таблицей doctors.
     */
    private Long staffUserId;

    /**
     * Отображаемое имя сотрудника (врача или администратора).
     * Денормализовано для отображения клиенту в заголовке диалога
     * («Чат с Dr. Ивановым») без дополнительного запроса.
     */
    private String staffUserName;

    /**
     * Момент создания чат-комнаты (UTC).
     * Используется для сортировки списка чатов по дате открытия
     * и отображения в заголовке диалога («Начато 15 мая»).
     */
    private LocalDateTime createdAt;

    /**
     * Количество непрочитанных сообщений для текущего пользователя.
     * Вычисляется в сервисном слое запросом:
     *   COUNT(*) WHERE room_id = :id AND sender_id != :currentUserId AND read = false
     * Используется для отображения бейджа на иконке чата («3 новых»).
     * Тип primitive long (не Long) — счётчик не может быть null.
     */
    private long unreadCount;

    /**
     * Текст последнего сообщения в комнате (preview, усечённый до ~100 символов).
     * Отображается в списке чатов под именем собеседника —
     * стандартный UI-паттерн мессенджеров (WhatsApp, Telegram).
     * Может быть null, если в комнате ещё не было сообщений.
     */
    private String lastMessage;

    /**
     * Время отправки последнего сообщения (UTC).
     * Используется для сортировки чатов по активности (сначала свежие)
     * и отображения временной метки в списке («15:42», «вчера», «15 мая»).
     * Null, если сообщений ещё не было.
     */
    private LocalDateTime lastMessageAt;
}
