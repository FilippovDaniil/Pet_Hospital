package com.hospital.dto.response;

import lombok.Builder;
import lombok.Data;

import java.time.LocalDateTime;

/**
 * DTO ОТВЕТА — одно сообщение в чате
 *
 * Возвращается API при загрузке истории диалога:
 * GET /api/client/chats/{roomId}/messages
 *
 * Содержит все данные, необходимые фронтенду для отрисовки «пузырька» сообщения:
 * текст, отправитель, время, флаг прочтения.
 * Фронтенд определяет сторону выравнивания (своё/чужое сообщение),
 * сравнивая senderId с ID текущего пользователя из JWT.
 *
 * Денормализация (senderName, senderRole) — осознанный trade-off:
 *   - Избегает N+1 запросов при рендеринге истории (не надо загружать профиль
 *     каждого отправителя отдельно)
 *   - Данные фиксируются на момент отправки: если врач сменит имя,
 *     старые сообщения сохранят исторически корректное значение
 */
@Data    // Lombok: генерирует геттеры, сеттеры, equals/hashCode, toString.
         // Нет смысла писать их вручную для DTO с 8 полями.
@Builder // Lombok: генерирует паттерн Builder для удобной сборки объекта в сервисе:
         // ChatMessageResponse.builder().id(...).roomId(...).build()
         // Альтернатива — @AllArgsConstructor, но Builder читаемее при > 4 аргументах.
public class ChatMessageResponse {

    /**
     * Первичный ключ сообщения в БД.
     * Используется фронтендом для пагинации (loadBefore/loadAfter),
     * а также для оптимистичной пометки сообщений прочитанными:
     * PUT /api/client/chats/{roomId}/messages/{id}/read
     */
    private Long id;

    /**
     * ID чат-комнаты, которой принадлежит сообщение.
     * Дублируется в ответе для удобства фронтенда при обработке
     * WebSocket-событий: клиент может определить, в какой чат
     * добавить пришедшее сообщение без дополнительного поля.
     */
    private Long roomId;

    /**
     * ID пользователя, отправившего сообщение (User.id).
     * Фронтенд сравнивает с currentUserId из JWT:
     *   senderId == currentUserId → своё сообщение (выравнивание вправо, синий цвет)
     *   senderId != currentUserId → чужое сообщение (выравнивание влево, серый цвет)
     */
    private Long senderId;

    /**
     * Отображаемое имя отправителя (fullName или username).
     * Показывается над «пузырьком» в групповых контекстах или
     * в нотификациях: «Новое сообщение от Иванов А.П.».
     * Денормализовано — не требует JOIN с таблицей users при выборке сообщений.
     */
    private String senderName;

    /**
     * Роль отправителя в виде строки: «ROLE_CLIENT», «ROLE_DOCTOR», «ROLE_ADMIN» и т.д.
     * Используется фронтендом для:
     *   - отображения бейджа роли рядом с именем («Врач», «Поддержка»)
     *   - стилизации сообщений (цвет аватара зависит от роли)
     * Передаётся строкой, а не enum, чтобы не связывать фронтенд с Java-перечислением.
     */
    private String senderRole;

    /**
     * Текст сообщения.
     * Максимальная длина ограничена на уровне входящего DTO (SendMessageRequest):
     * @Size(max = 4000) — соответствует типу TEXT в PostgreSQL без практических ограничений,
     * но разумный лимит защищает от злоупотреблений.
     */
    private String content;

    /**
     * Момент отправки сообщения (UTC, сохраняется в БД).
     * Отображается в UI под «пузырьком»: «14:35», «вчера», «15 мая».
     * UTC на бэкенде, конвертация в локальный часовой пояс — на фронтенде.
     */
    private LocalDateTime sentAt;

    /**
     * Флаг прочтения сообщения получателем.
     * true  — сообщение открыто и прочитано получателем
     * false — новое непрочитанное сообщение (показывается синяя галочка / бейдж)
     *
     * Тип primitive boolean (не Boolean): null-значение не имеет смысла —
     * сообщение либо прочитано, либо нет.
     */
    private boolean read;
}
