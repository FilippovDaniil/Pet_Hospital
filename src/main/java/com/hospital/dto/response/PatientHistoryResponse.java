package com.hospital.dto.response;

import lombok.Builder;
import lombok.Data;

import java.util.List;

/**
 * DTO ОТВЕТА — сводная история болезни пациента
 *
 * Возвращается API при запросах:
 *   GET /api/doctor/patients/{id}/history  — полная история (врач видит всё)
 *   GET /api/client/history/my             — история текущего клиента
 *                                            (только записи с visibleToClient = true
 *                                             и активные документы)
 *
 * Цель объекта — агрегировать все клинически значимые данные пациента
 * в одном ответе, чтобы фронтенд мог отрисовать страницу «История болезни»
 * за один HTTP-запрос (вместо двух отдельных: /notes и /documents).
 *
 * Архитектурное решение — плоская агрегация (не вложенная по датам):
 *   - Сортировку и группировку по дате делает фронтенд (гибче)
 *   - Бэкенд возвращает полные списки — нет риска потери данных из-за
 *     серверной группировки
 *   - При необходимости пагинации — расширяем структуру полями page/totalPages
 *     без изменения клиентского кода парсинга notes и documents
 */
@Data    // Lombok: геттеры, сеттеры, equals/hashCode, toString.
         // Достаточно для неизменяемого (по сути) агрегирующего DTO.
@Builder // Lombok: Builder упрощает создание объекта в сервисе:
         // PatientHistoryResponse.builder()
         //     .patientId(patient.getId())
         //     .notes(noteResponses)
         //     .documents(docResponses)
         //     .build()
public class PatientHistoryResponse {

    /**
     * ID пациента (Patient.id), чья история возвращается.
     * Позволяет клиентскому коду идентифицировать, для кого
     * предназначен ответ, особенно при кэшировании или асинхронной загрузке.
     */
    private Long patientId;

    /**
     * Полное имя пациента (денормализовано из Patient.fullName).
     * Отображается в заголовке страницы истории болезни:
     * «История болезни: Иванова Мария Сергеевна».
     * Устраняет необходимость отдельного запроса к /api/patients/{id}
     * только ради имени.
     */
    private String patientName;

    /**
     * Список врачебных записей пациента (диагнозы, наблюдения, заметки).
     *
     * Порядок элементов: как правило, по убыванию createdAt (новые первыми),
     * но сортировка выполняется в сервисном слое — DTO не зависит от порядка.
     *
     * Для клиента: содержит только записи с visibleToClient = true.
     * Для врача: содержит все записи пациента, включая служебные.
     *
     * Пустой список (не null) если записей нет — клиенту не нужна проверка на null.
     */
    private List<PatientNoteResponse> notes;

    /**
     * Список медицинских документов пациента (рецепты, больничные, справки и т.д.).
     *
     * Для клиента: только активные документы (active = true).
     * Для врача: все документы, включая аннулированные (для полноты истории).
     *
     * Пустой список (не null) если документов нет.
     * Сортировка по убыванию issuedAt — актуальные документы наверху.
     */
    private List<MedicalDocumentResponse> documents;
}
