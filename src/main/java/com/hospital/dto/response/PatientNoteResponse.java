package com.hospital.dto.response;

import lombok.Builder;
import lombok.Data;

import java.time.LocalDateTime;

/**
 * DTO ОТВЕТА — врачебная запись в истории болезни пациента
 *
 * Возвращается API при запросах:
 *   GET /api/doctor/patients/{id}/notes  — все записи пациента (видит врач)
 *   GET /api/client/history/my           — только записи с visibleToClient = true
 *
 * Принципиальное разделение видимости:
 *   - Врач видит все записи пациента, включая служебные заметки (NOTE)
 *   - Клиент видит только те записи, где visibleToClient = true —
 *     фильтрация выполняется в сервисном слое до маппинга в этот DTO
 *
 * Денормализация patientName и doctorName позволяет рендерить список записей
 * без дополнительных запросов к /api/patients и /api/doctors.
 *
 * Разделение type / typeLabel — стандартный паттерн проекта:
 *   type      — для логики фронтенда (условный рендеринг, фильтры)
 *   typeLabel — для отображения пользователю («Диагноз», «Наблюдение», «Заметка»)
 */
@Data    // Lombok: геттеры, сеттеры, equals/hashCode, toString.
         // Стандартный набор для read-only DTO.
@Builder // Lombok: Builder-паттерн для удобной сборки в сервисном слое:
         // PatientNoteResponse.builder().id(note.getId()).type(...).build()
public class PatientNoteResponse {

    /**
     * Первичный ключ записи в БД.
     * Используется для редактирования или удаления конкретной записи:
     * PUT /api/doctor/notes/{id}, DELETE /api/doctor/notes/{id}
     */
    private Long id;

    /**
     * ID пациента (Patient.id), которому принадлежит запись.
     * Нужен фронтенду для «хлебной крошки» и обратной ссылки на карточку пациента.
     * В ответе на запрос «записи конкретного пациента» это поле дублирует
     * параметр пути, но обеспечивает самодостаточность DTO при WebSocket-событиях.
     */
    private Long patientId;

    /**
     * Полное имя пациента (денормализовано из Patient.fullName).
     * Отображается в заголовке записи в режиме списка:
     * «Иванова М.С. | Диагноз | 15.05.2026»
     */
    private String patientName;

    /**
     * ID врача (Doctor.id или User.id), создавшего запись.
     * Используется для фильтрации записей по конкретному врачу
     * и для перехода к профилю автора записи.
     */
    private Long doctorId;

    /**
     * Полное имя врача — автора записи (денормализовано).
     * Важно для аудита и объяснения пациенту: «Кто и что написал».
     * Также нужно при просмотре сводной истории болезни нескольким врачам
     * одновременно — сразу видно, чья запись.
     */
    private String doctorName;

    /**
     * Тип записи в виде строки: «DIAGNOSIS», «OBSERVATION», «NOTE».
     * Машиночитаемое значение PatientNoteType.name() —
     * фронтенд использует для выбора иконки и фильтрации по вкладкам.
     */
    private String type;

    /**
     * Человекочитаемая метка типа: «Диагноз», «Наблюдение», «Заметка».
     * Формируется в сервисном слое через switch/Map<PatientNoteType, String>.
     * Фронтенд отображает в UI без дополнительных словарей.
     */
    private String typeLabel;

    /**
     * Содержимое записи — основной текст, введённый врачом.
     * Структура произвольная: может включать коды МКБ-10 для диагноза,
     * параметры осмотра для наблюдения или свободный текст для заметки.
     */
    private String content;

    /**
     * Флаг видимости записи для клиента-пациента.
     * true  — пациент видит эту запись в своём личном кабинете
     * false — запись только для персонала (служебная заметка, рабочие пометки)
     *
     * При формировании ответа для клиента (GET /api/client/history/my)
     * сервис фильтрует записи по visibleToClient = true до маппинга в DTO,
     * поэтому клиент никогда не получит запись с false, даже если поле здесь false.
     * Поле присутствует в DTO для интерфейса врача, где нужно показать
     * флаг «видно пациенту» рядом с каждой записью.
     */
    private boolean visibleToClient;

    /**
     * Дата и время создания записи (UTC, устанавливается автоматически).
     * Отображается в заголовке: «15.05.2026 в 14:35».
     * Используется для хронологической сортировки истории болезни.
     */
    private LocalDateTime createdAt;
}
