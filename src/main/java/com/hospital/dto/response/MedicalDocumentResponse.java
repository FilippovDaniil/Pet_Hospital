package com.hospital.dto.response;

import lombok.Builder;
import lombok.Data;

import java.time.LocalDate;
import java.time.LocalDateTime;

/**
 * DTO ОТВЕТА — медицинский документ, выданный врачом пациенту
 *
 * Возвращается API при запросах:
 *   GET /api/doctor/documents          — список документов, выданных текущим врачом
 *   GET /api/client/documents/my       — документы текущего клиента-пациента
 *   POST /api/doctor/documents         — тело ответа после создания документа
 *
 * Денормализация (patientName, doctorName, doctorSpecialty) осознанна:
 *   - Список документов рендерится без N+1 запросов
 *   - Фронтенд показывает «Рецепт от Иванова А.П. (Терапевт)» в одной карточке
 *     без дополнительной загрузки профилей врача и пациента
 *
 * Разделение type / typeLabel:
 *   - type       — машиночитаемое значение enum («PRESCRIPTION», «SICK_LEAVE»):
 *                  используется для условной логики на фронтенде (иконка, цвет)
 *   - typeLabel  — человекочитаемая локализованная метка («Рецепт», «Больничный лист»):
 *                  отображается пользователю; локализация выполняется в сервисном слое
 */
@Data    // Lombok: генерирует геттеры, сеттеры, equals/hashCode, toString —
         // стандартный набор для DTO, которое только читается фронтендом.
@Builder // Lombok: позволяет собирать DTO цепочкой:
         // MedicalDocumentResponse.builder().id(doc.getId()).patientName(...).build()
         // Читаемее конструктора с 13 параметрами.
public class MedicalDocumentResponse {

    /**
     * Первичный ключ документа в БД.
     * Используется для ссылки на конкретный документ при скачивании
     * или изменении статуса: PUT /api/doctor/documents/{id}/deactivate
     */
    private Long id;

    /**
     * ID пациента (Patient.id), для которого выдан документ.
     * Используется фронтендом для перехода в карточку пациента:
     * «Открыть профиль» → /api/patients/{patientId}
     */
    private Long patientId;

    /**
     * Полное имя пациента (денормализовано из Patient.fullName).
     * Отображается в заголовке карточки документа.
     * Врачу показывает, чей это документ; пациенту — подтверждает, что документ его.
     */
    private String patientName;

    /**
     * ID врача (Doctor.id / User.id), выдавшего документ.
     * Используется для фильтрации документов в списке врача
     * и для перехода к профилю доктора с карточки документа.
     */
    private Long doctorId;

    /**
     * Полное имя врача (денормализовано из Doctor/User).
     * Отображается в карточке документа: «Выдан: Иванов А.П.»
     * Необходимо клиенту, чтобы знать, кто подписал документ.
     */
    private String doctorName;

    /**
     * Специальность врача (денормализовано из Doctor.specialty).
     * Отображается рядом с именем: «Иванов А.П. | Терапевт».
     * Позволяет клиенту убедиться, что документ выдан профильным специалистом.
     */
    private String doctorSpecialty;

    /**
     * Тип документа в виде строки (машиночитаемое): «PRESCRIPTION», «SICK_LEAVE» и т.д.
     * Фронтенд использует для:
     *   - выбора иконки (рецепт ≠ больничный)
     *   - условного отображения полей (validUntil показывается только для типов,
     *     где срок действия имеет смысл)
     *   - фильтрации списка по типу документа
     */
    private String type;

    /**
     * Человекочитаемая метка типа на языке интерфейса: «Рецепт», «Направление» и т.д.
     * Формируется в сервисном слое, чтобы не тащить логику локализации на фронтенд.
     * При добавлении нового языка достаточно изменить сервис — DTO не меняется.
     */
    private String typeLabel;

    /**
     * Краткий заголовок документа, введённый врачом при создании.
     * Отображается в списке документов как основной текст строки:
     * «Рецепт: Амоксициллин 500мг» или «Направление на ОАК, биохимию».
     */
    private String title;

    /**
     * Полный текст (содержание) документа.
     * Показывается при открытии карточки документа или его печати.
     * Может содержать разметку: инструкции по приёму, коды МКБ-10, реквизиты.
     */
    private String content;

    /**
     * Дата и время выдачи документа (UTC, фиксируется автоматически при сохранении).
     * Является официальной датой документа: «Выдан 15.05.2026 14:35».
     * LocalDateTime (не LocalDate) — точное время важно для хронологии в истории болезни.
     */
    private LocalDateTime issuedAt;

    /**
     * Дата окончания действия документа (может быть null для бессрочных).
     * Присутствует у рецептов, больничных листов, справок.
     * Тип LocalDate (без времени) — срок действия измеряется днями, не минутами.
     * Фронтенд отображает предупреждение, если дата прошла.
     */
    private LocalDate validUntil;

    /**
     * Флаг актуальности документа.
     * true  — документ действителен и отображается в активном списке
     * false — документ аннулирован или истёк (soft-деактивация, аналог soft-delete):
     *         данные сохраняются для истории болезни, но в основной список не попадают.
     *
     * Такой подход согласован с мягким удалением пациентов (Patient.active = false).
     */
    private boolean active;
}
