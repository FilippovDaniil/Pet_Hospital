package com.hospital.service;

import com.hospital.dto.request.SendMessageRequest;
import com.hospital.dto.response.ChatMessageResponse;
import com.hospital.dto.response.ChatRoomResponse;
import com.hospital.entity.User;

import java.util.List;

/**
 * Сервисный интерфейс для управления чатами между клиентами и персоналом больницы.
 *
 * <p>Ключевые архитектурные решения:
 * <ul>
 *   <li><b>Передача {@link User} вместо ID</b>: все методы принимают объект
 *       {@code User}, а не {@code Long userId}. Это позволяет сервису работать
 *       с уже аутентифицированным пользователем из Security-контекста без
 *       дополнительного запроса к БД для загрузки пользователя по ID.</li>
 *   <li><b>Паттерн get-or-create для комнат</b>: методы {@link #getOrCreateSupportRoom}
 *       и {@link #getOrCreateDoctorRoom} возвращают существующую комнату или создают
 *       новую, если она ещё не существует. Это идемпотентное поведение упрощает
 *       клиентский код: не нужно проверять существование комнаты перед открытием чата.</li>
 *   <li><b>Проверка доступа к комнате на уровне сервиса</b>: методы {@link #getRoomMessages}
 *       и {@link #pollMessages} получают {@code requester} и обязаны проверить, что
 *       пользователь является участником данной комнаты. Это централизует авторизацию
 *       и предотвращает чтение чужих переписок даже при прямом обращении к API.</li>
 *   <li><b>Polling вместо WebSocket</b>: метод {@link #pollMessages} с параметром
 *       {@code sinceId} поддерживает short-polling — упрощённую альтернативу WebSocket.
 *       Клиент периодически запрашивает только новые сообщения, не перезагружая историю.</li>
 * </ul>
 */
public interface ChatService {

    /**
     * Возвращает существующую SUPPORT-комнату клиента или создаёт новую.
     *
     * <p>Реализует паттерн get-or-create: при первом обращении клиента создаётся
     * комната без привязки к конкретному сотруднику ({@code staffUser = null}).
     * При повторных обращениях возвращается та же комната.
     *
     * @param client аутентифицированный пользователь с ролью ROLE_CLIENT
     * @return DTO созданной или существующей SUPPORT-комнаты
     */
    ChatRoomResponse getOrCreateSupportRoom(User client);

    /**
     * Возвращает список всех SUPPORT-комнат для администратора.
     *
     * <p>Используется в интерфейсе администратора для отображения очереди обращений
     * от клиентов. Список упорядочен от новых обращений к старым.
     *
     * @return список всех SUPPORT-комнат в системе
     */
    List<ChatRoomResponse> getAllSupportRooms();

    /**
     * Возвращает существующую DOCTOR_CLIENT-комнату для пары клиент–врач или создаёт новую.
     *
     * <p>Реализует паттерн get-or-create. Эндпоинт могут вызывать обе стороны:
     * <ul>
     *   <li>{@code ROLE_CLIENT} передаёт {@code otherUserId = userId врача}</li>
     *   <li>{@code ROLE_DOCTOR} передаёт {@code otherUserId = userId клиента}</li>
     * </ul>
     * Реализация сама определяет роли по {@code caller.getRole()} и расставляет
     * clientUser / staffUser корректно независимо от инициатора.
     *
     * @param caller      аутентифицированный пользователь (ROLE_CLIENT или ROLE_DOCTOR)
     * @param otherUserId ID второй стороны: врача (если caller — клиент) или клиента (если caller — врач)
     * @return DTO созданной или существующей DOCTOR_CLIENT-комнаты
     */
    ChatRoomResponse getOrCreateDoctorRoom(User caller, Long otherUserId);

    /**
     * Возвращает список всех чат-комнат данного врача с клиентами.
     *
     * <p>Используется в интерфейсе врача для просмотра входящих сообщений от пациентов.
     * Список упорядочен от новых комнат к старым.
     *
     * @param doctorUser аутентифицированный пользователь с ролью ROLE_DOCTOR
     * @return список DOCTOR_CLIENT-комнат данного врача
     */
    List<ChatRoomResponse> getDoctorRooms(User doctorUser);

    /**
     * Возвращает список всех чат-комнат клиента (SUPPORT и DOCTOR_CLIENT).
     *
     * <p>Используется на главном экране чатов клиентского портала для отображения
     * всех активных переписок: с поддержкой и с врачами.
     *
     * @param client аутентифицированный пользователь с ролью ROLE_CLIENT
     * @return список всех чат-комнат данного клиента, упорядоченный от новых к старым
     */
    List<ChatRoomResponse> getMyRooms(User client);

    /**
     * Возвращает полную историю сообщений в указанной комнате.
     *
     * <p>Перед возвратом сообщений реализация обязана проверить, что {@code requester}
     * является участником данной комнаты (клиентом, администратором или врачом-собеседником).
     * Несанкционированный доступ должен завершаться исключением с кодом 403.
     *
     * @param roomId    идентификатор чат-комнаты
     * @param requester аутентифицированный пользователь, запрашивающий сообщения
     * @return список сообщений в хронологическом порядке (от старых к новым)
     */
    List<ChatMessageResponse> getRoomMessages(Long roomId, User requester);

    /**
     * Отправляет новое сообщение от имени указанного пользователя в комнату.
     *
     * <p>Реализация должна проверить, что {@code sender} является участником комнаты.
     * После сохранения сообщения счётчик непрочитанных для других участников увеличивается.
     *
     * @param roomId  идентификатор целевой чат-комнаты
     * @param request DTO с текстом сообщения
     * @param sender  аутентифицированный пользователь-отправитель
     * @return DTO созданного сообщения с заполненными полями {@code id} и {@code sentAt}
     */
    ChatMessageResponse sendMessage(Long roomId, SendMessageRequest request, User sender);

    /**
     * Возвращает только сообщения, поступившие после сообщения с указанным ID (для polling).
     *
     * <p>Используется для реализации short-polling: клиент сохраняет ID последнего
     * полученного сообщения и периодически вызывает этот метод. Возвращается только
     * дельта (новые сообщения), а не вся история. Это снижает нагрузку на сеть и сервер
     * по сравнению с повторным вызовом {@link #getRoomMessages}.
     *
     * <p>Аналогично {@link #getRoomMessages}, реализация обязана проверить права доступа.
     *
     * @param roomId    идентификатор чат-комнаты
     * @param sinceId   ID последнего известного сообщения; возвращаются сообщения с ID строго больше
     * @param requester аутентифицированный пользователь, запрашивающий сообщения
     * @return список новых сообщений (может быть пустым если новых сообщений нет)
     */
    List<ChatMessageResponse> pollMessages(Long roomId, Long sinceId, User requester);
}
