package com.hospital.entity;

/**
 * ТИП МЕДИЦИНСКОГО ДОКУМЕНТА — перечисление видов документов, выдаваемых врачом
 *
 * Каждый тип определяет:
 *   - юридическую форму документа (рецепт, больничный, справка и т.д.)
 *   - правила отображения в клиентском портале (какие поля актуальны,
 *     нужна ли дата окончания validUntil, показывать ли пациенту)
 *   - логику архивации (например, истёкший больничный помечается неактивным)
 *
 * Хранится в БД как строка (EnumType.STRING) — читаемо и устойчиво
 * к изменению порядка констант при рефакторинге.
 *
 * Расширение: добавить новую константу сюда, при необходимости добавить
 * человекочитаемую метку в сервисный слой (typeLabel в DTO-ответе).
 */
public enum MedicalDocumentType {

    /**
     * РЕЦЕПТ — документ, дающий право на получение лекарственного препарата.
     *
     * Особенности:
     *   - Всегда имеет срок действия (validUntil): обычно 30–60 дней
     *   - Содержит название препарата, дозировку и режим приёма
     *   - Отображается клиенту в разделе «Мои документы»
     *   - Актуален только если active = true и validUntil не истёк
     */
    PRESCRIPTION,

    /**
     * НАПРАВЛЕНИЕ — документ для посещения другого специалиста или госпитализации.
     *
     * Особенности:
     *   - Указывает специальность / отделение, к которому направляется пациент
     *   - Срок действия validUntil опционален (зависит от типа направления)
     *   - После использования может быть помечен неактивным (active = false)
     *   - Примеры: направление к кардиологу, на МРТ, на госпитализацию
     */
    REFERRAL,

    /**
     * БОЛЬНИЧНЫЙ ЛИСТ — документ, удостоверяющий временную нетрудоспособность.
     *
     * Особенности:
     *   - Обязательно имеет дату закрытия (validUntil) — дата выхода на работу
     *   - Имеет строгую юридическую форму; content содержит номер листка
     *   - Отображается клиенту для предъявления работодателю
     *   - По истечении validUntil система может автоматически снять активность
     */
    SICK_LEAVE,

    /**
     * НАПРАВЛЕНИЕ НА АНАЛИЗЫ — документ для прохождения лабораторных
     * или инструментальных исследований.
     *
     * Особенности:
     *   - Перечисляет конкретные анализы / процедуры (в поле content)
     *   - Срок действия обычно 10–14 дней
     *   - После получения результатов связывается с записью врача (OBSERVATION/DIAGNOSIS)
     *   - Примеры: ОАК, биохимия крови, ЭКГ, УЗИ органов брюшной полости
     */
    ANALYSIS_ORDER,

    /**
     * СПРАВКА — медицинское заключение общего назначения.
     *
     * Особенности:
     *   - Наиболее универсальный тип: охватывает справки в бассейн, на работу,
     *     о состоянии здоровья, об отсутствии противопоказаний и т.д.
     *   - Срок действия validUntil зависит от цели справки (обычно 3–12 месяцев)
     *   - Содержит печать врача и медицинской организации (указывается в content)
     *   - Отображается клиенту для скачивания / предъявления
     */
    CERTIFICATE
}
