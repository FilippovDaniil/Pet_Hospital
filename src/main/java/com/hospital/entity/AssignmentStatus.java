package com.hospital.entity;

/**
 * Статус назначения процедуры.
 *
 * Жизненный цикл: ACTIVE → DONE | CANCELLED.
 * Обратный переход не предусмотрен: выполненное или отменённое назначение
 * не может стать активным снова (для повторного назначения создаётся новая запись).
 *
 * Хранится как строка (EnumType.STRING в NurseAssignment).
 */
public enum AssignmentStatus {
    ACTIVE,    // назначение создано и ожидает выполнения
    DONE,      // процедура выполнена медсестрой
    CANCELLED  // назначение отменено (по любой причине)
}
