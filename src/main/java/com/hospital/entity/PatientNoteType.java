package com.hospital.entity;

/**
 * ТИП ЗАПИСИ В ИСТОРИИ БОЛЕЗНИ — перечисление видов врачебных записей по пациенту
 *
 * Классифицирует каждую запись PatientNote по её медицинскому смыслу.
 * Это позволяет:
 *   - Фильтровать записи в интерфейсе (вкладки «Диагнозы», «Наблюдения», «Заметки»)
 *   - Управлять видимостью: диагнозы и наблюдения чаще помечаются visibleToClient = true,
 *     произвольные заметки врача — по усмотрению
 *   - Строить сводку по пациенту (PatientHistoryResponse) с разбивкой по типам
 *   - В будущем — применять разные шаблоны печатных форм для каждого типа
 *
 * Хранится в БД как строка (EnumType.STRING) для читаемости и
 * независимости от порядка объявления констант.
 */
public enum PatientNoteType {

    /**
     * ДИАГНОЗ — формальное врачебное заключение о заболевании пациента.
     *
     * Особенности:
     *   - Как правило, содержит код МКБ-10 и развёрнутую формулировку
     *   - Обычно показывается пациенту (visibleToClient = true): он должен
     *     знать свой диагноз
     *   - Является основанием для выписки рецептов (PRESCRIPTION)
     *     и направлений (REFERRAL)
     *   - Может быть уточнён или изменён последующей записью того же типа
     */
    DIAGNOSIS,

    /**
     * НАБЛЮДЕНИЕ — запись об осмотре, динамике состояния или результатах обследования.
     *
     * Особенности:
     *   - Фиксирует жалобы пациента, объективные данные осмотра,
     *     результаты анализов и инструментальных исследований
     *   - Показывается пациенту по решению врача (visibleToClient на усмотрение):
     *     некоторые технические данные осмотра могут не отображаться
     *   - Примеры: «АД 130/85, ЧСС 72 уд/мин», «УЗИ: без патологии»,
     *     «Жалобы на головную боль 3 дня»
     */
    OBSERVATION,

    /**
     * ЗАМЕТКА — произвольная врачебная запись, не вписывающаяся в стандартные категории.
     *
     * Особенности:
     *   - Используется для внутренних пометок врача: напоминания, рабочие заметки,
     *     координация с коллегами, планы лечения в черновом виде
     *   - По умолчанию НЕ показывается пациенту (visibleToClient = false),
     *     так как может содержать служебную информацию
     *   - Не имеет строгой структуры — формат content произвольный
     */
    NOTE
}
