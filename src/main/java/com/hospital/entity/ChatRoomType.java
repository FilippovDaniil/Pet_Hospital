package com.hospital.entity;

/**
 * ТИП ЧАТ-КОМНАТЫ — перечисление видов диалогов в системе обмена сообщениями
 *
 * Определяет семантику каждой комнаты: кто является участниками,
 * при каких условиях комната создаётся и какие права доступа применяются.
 *
 * Используется в сущности ChatRoom для:
 *   - маршрутизации новых сообщений нужному получателю
 *   - ограничения доступа (ROLE_CLIENT видит только свои комнаты,
 *     ROLE_DOCTOR — только DOCTOR_CLIENT-комнаты со своим участием)
 *   - фильтрации в интерфейсах (разные вкладки «Поддержка» и «Врач»)
 *
 * Архитектурное решение — enum вместо строки VARCHAR:
 *   - Типобезопасность на уровне компилятора: невозможно передать
 *     несуществующий тип без ошибки компиляции
 *   - JPA по умолчанию хранит имя константы (@Enumerated(STRING)),
 *     что читаемо в БД и не ломается при изменении порядка значений
 *     (в отличие от ORDINAL, который зависит от позиции в enum)
 *   - Добавление нового типа — одна строка здесь, без миграции схемы
 */
public enum ChatRoomType {

    /**
     * ПОДДЕРЖКА — диалог клиента с сотрудником службы поддержки.
     *
     * Участники:
     *   - clientUserId: пользователь с ролью ROLE_CLIENT (пациент/клиент)
     *   - staffUserId:  пользователь с ролью ROLE_ADMIN или ROLE_NURSE
     *
     * Сценарии использования:
     *   - Клиент задаёт вопрос об условиях обслуживания, расписании, ценах
     *   - Клиент подаёт жалобу или оставляет отзыв
     *   - Администратор информирует об изменении статуса записи
     *
     * Жизненный цикл: создаётся вручную клиентом через кнопку «Написать в поддержку»
     * или администратором при обработке обращения. Не закрывается автоматически.
     */
    SUPPORT,

    /**
     * ВРАЧ–КЛИЕНТ — персональный диалог между врачом и его пациентом.
     *
     * Участники:
     *   - clientUserId: пользователь с ролью ROLE_CLIENT (пациент)
     *   - staffUserId:  пользователь с ролью ROLE_DOCTOR (лечащий врач)
     *
     * Важная деталь реализации: staffUserId здесь равен User.id врача,
     * что позволяет фильтровать чаты врача запросом
     * «WHERE type = DOCTOR_CLIENT AND staff_user_id = :currentUserId»
     * без дополнительного JOIN с таблицей doctors.
     *
     * Сценарии использования:
     *   - Врач консультирует пациента удалённо после очного приёма
     *   - Врач уточняет анамнез перед следующим визитом
     *   - Пациент задаёт вопрос по назначенному лечению
     *
     * Жизненный цикл: может создаваться автоматически при подтверждении
     * Appointment или вручную врачом/администратором.
     */
    DOCTOR_CLIENT
}
